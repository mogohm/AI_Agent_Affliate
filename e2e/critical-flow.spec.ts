test("critical flow: CSV import → commission ranking → script → storyboard → hybrid render → preview → MP4 download → approve", async ({ page }) => {
  const request = page.request;
  await login(page);

  // 1) Import CSV with mapping preview
  await page.goto("/products/import");
  await page.getByTestId("csv-input").setInputFiles(path.join(__dirname, "fixtures", "products.csv"));
  await page.getByTestId("authorize-checkbox").check();
  await page.getByRole("button", { name: /นำเข้า .* แถวที่ผ่าน/ }).click();
  await expect(page.getByTestId("import-result")).toBeVisible();
  await expect(page.getByTestId("import-result")).toContainText("3");

  // 2) Explorer sorted by commission/order (default) — E2E-1001: min(1590×15%, cap 500) = 238.5 ranks first
  await page.goto("/products?search=E2E");
  const rows = page.getByTestId("product-row");
  await expect(rows).toHaveCount(3);
  await expect(rows.first()).toContainText("ไมโครโฟน");
  const amounts = await page.getByTestId("est-commission").allTextContents();
  const nums = amounts.map((s) => Number(s.replace(/[^\d.]/g, "")));
  expect([...nums].sort((a, b) => b - a)).toEqual(nums);

  // 3) Select product → Studio → create project (script generation auto-queued)
  await rows.first().getByRole("link", { name: /ทำคลิป/ }).click();
  await expect(page).toHaveURL(/\/studio\?offerId=/);
  await page.getByTestId("create-project").click();
  await expect(page).toHaveURL(/\/studio\/[0-9a-f-]{36}/);
  const projectId = page.url().split("/studio/")[1].split(/[?#]/)[0];

  // 4) Script + storyboard generated by the worker
  await expect(page.getByTestId("scene").first()).toBeVisible({ timeout: 60_000 });
  expect(await page.getByTestId("scene").count()).toBeGreaterThanOrEqual(3);

  // 5) Approve script → render (hybrid FFmpeg) → preview video
  await page.getByTestId("approve-script").click();
  await expect(page.getByTestId("rendered-video")).toBeVisible({ timeout: 180_000 });

  // 6) MP4 is downloadable and valid-looking
  const proj = await (await request.get(`/api/video-projects/${projectId}`)).json();
  const assetId = proj.project?.outputAssetId ?? proj.outputAssetId;
  expect(assetId).toBeTruthy();
  const mp4 = await request.get(`/api/files/${assetId}?download=1`);
  expect(mp4.status()).toBe(200);
  expect(mp4.headers()["content-type"]).toContain("video/mp4");
  const body = await mp4.body();
  expect(body.length).toBeGreaterThan(10_000);
  expect(body.subarray(4, 8).toString("ascii")).toBe("ftyp");

  // 7) Human approval → export
  await page.getByTestId("approve-video").click();
  await expect(page.getByTestId("export-video")).toBeVisible();
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByTestId("export-video").click()]);
  expect(download.suggestedFilename()).toMatch(/\.mp4$/);

  // 8) Queue shows succeeded jobs; library lists the clip
  await page.goto("/queue");
  await expect(page.getByTestId("job-row").first()).toBeVisible();
  await page.goto("/library");
  await expect(page.getByTestId("library-card").first()).toBeVisible();
});

test("settings: admin can save budget; viewer is denied", async ({ page, browser }) => {
  await login(page);
  await page.goto("/settings?tab=budget");
  await expect(page.getByText("งบรายวัน", { exact: false }).first()).toBeVisible();

  const res = await page.request.get("/api/settings/budget");
  expect(res.status()).toBe(200);
  const budget = await res.json();
  const save = await page.request.patch("/api/settings/budget", { data: { ...(budget.budget ?? budget), dailyUsd: 7 } });
  expect(save.status()).toBe(200);

  const ctx = await browser.newContext();
  const viewer = await ctx.newPage();
  await login(viewer, "viewer@example.com");
  expect((await viewer.request.patch("/api/settings/budget", { data: { dailyUsd: 999 } })).status()).toBe(403);
  expect((await viewer.request.get("/api/users")).status()).toBe(403);
  expect((await viewer.request.post("/api/products", { data: {} })).status()).toBe(403);
  await ctx.close();
});
